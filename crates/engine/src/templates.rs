#[cfg(test)]
mod tests {
    use super::*;
    use crate::grid::Grid;
    use crate::rules::british_rules;

    #[test]
    fn every_template_passes_british_rules() {
        assert_eq!(TEMPLATES.len(), 6);
        for t in TEMPLATES {
            let g = Grid::from_rows(t.rows);
            assert!(
                british_rules(&g).is_empty(),
                "{}: {:?}",
                t.name,
                british_rules(&g)
            );
            let n = t.rows.len();
            for r in 0..n {
                for c in 0..n {
                    let a = t.rows[r].as_bytes()[c];
                    let b = t.rows[n - 1 - r].as_bytes()[n - 1 - c];
                    assert_eq!(a, b, "{} not symmetric at {r},{c}", t.name);
                }
            }
        }
    }
}
